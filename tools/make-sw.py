#!/usr/bin/env python3
"""Rebuild sw.js so the game works offline.

Run from the repository root after any change to the game's files:
    python3 tools/make-sw.py
It lists every file the game needs and stamps a new cache version, so phones
that already installed the game pick up the update the next time they are online.
"""
import os, json, time, hashlib

SKIP_DIRS = {'.git', 'tools'}
SKIP_FILES = {'sw.js', 'README.md', '.nojekyll', '.DS_Store'}

files = []
for root, dirs, names in os.walk('.'):
    dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
    for n in sorted(names):
        if n in SKIP_FILES:
            continue
        files.append(os.path.join(root, n).replace(os.sep, '/'))
files.sort()
hashes = {f: hashlib.sha1(open(f, 'rb').read()).hexdigest()[:10] for f in files}
version = time.strftime('%Y%m%d-%H%M%S', time.gmtime())

SW = r'''// Generated by tools/make-sw.py. Do not edit by hand.
// Keeps a copy of the whole game on the device so it opens and plays with no connection.
const VERSION = '__VERSION__';
const CACHE = 'moked100-' + VERSION;
const HASHES = __FILES__;

self.addEventListener('install', e => {
  // Only files that changed since the last version are downloaded again; the rest are copied from the old saved copy.
  // One file at a time, so a single failed download does not cancel the whole install.
  e.waitUntil((async () => {
    const c = await caches.open(CACHE);
    await c.add(new Request('./', {cache: 'reload'}));
    let prev = {}, prevCache = null;
    for (const k of (await caches.keys()).filter(k => k.startsWith('moked100-') && k !== CACHE)) {
      const oc = await caches.open(k), m = await oc.match('./__hashes');
      if (m) { try { prev = await m.json(); prevCache = oc; } catch (err) {} }
    }
    for (const f of Object.keys(HASHES)) {
      try {
        if (prevCache && prev[f] === HASHES[f]) { const old = await prevCache.match(f); if (old) { await c.put(f, old); continue; } }
        await c.add(new Request(f, {cache: 'reload'}));
      } catch (err) {}
    }
    await c.put('./__hashes', new Response(JSON.stringify(HASHES), {headers: {'Content-Type': 'application/json'}}));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('moked100-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// Audio and video ask for byte ranges; answer those from the saved copy too.
async function ranged(req, res) {
  const range = /bytes=(\d+)-(\d*)/.exec(req.headers.get('range') || '');
  if (!range) return res;
  const buf = await res.arrayBuffer(), start = +range[1], end = range[2] ? Math.min(+range[2], buf.byteLength - 1) : buf.byteLength - 1;
  return new Response(buf.slice(start, end + 1), {status: 206, statusText: 'Partial Content', headers: {
    'Content-Type': res.headers.get('Content-Type') || 'application/octet-stream',
    'Content-Range': 'bytes ' + start + '-' + end + '/' + buf.byteLength, 'Content-Length': String(end - start + 1), 'Accept-Ranges': 'bytes'}});
}

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url), own = url.origin === self.location.origin;
  const fonts = url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com';
  if (!own && !fonts) return;
  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    if (req.mode === 'navigate') {                          // the page itself: newest when online, saved copy when not
      try { const fresh = await fetch(req.url, {cache: 'no-store', credentials: 'same-origin'}); if (fresh.ok) cache.put('./', fresh.clone()); return fresh; }
      catch (err) { return (await cache.match('./')) || (await cache.match('./index.html')) || Response.error(); }
    }
    const hit = await cache.match(req, {ignoreSearch: true});
    if (hit) return req.headers.has('range') ? ranged(req, hit) : hit;
    try {
      const res = await fetch(req);
      if (res.ok && res.status === 200) cache.put(req, res.clone());
      else if (res.type === 'opaque') cache.put(req, res.clone());
      return res;
    } catch (err) { return Response.error(); }
  })());
});
'''
open('sw.js', 'w', encoding='utf8').write(SW.replace('__VERSION__', version).replace('__FILES__', json.dumps(hashes, ensure_ascii=False, indent=0)))
print('sw.js written:', len(files), 'files, version', version)
